//位运算符

//& 按位与
// let numOne = 5;
// let numTwo = 3;
// let result = numOne & numTwo;
// console.log(result);
//把5和3转换成二进制数(短除法)
// 5 =》 00000101     3 =》 00000011
/*
   高位         低位
    2^6         2^0   级别
     00000101
&    00000011   对应位置上的值只有都为1，结果才为1，否则为0
  -----------------
     00000001

     二进制按位与计算后的结果为00000001

把二进制数转为十进制数
0           0    0    0    0    0    0   1
符号位      2^6  2^5  2^4  2^3  2^2  2^1  2^0
          0*2^6 + 0*2^5 + 0*2^4 + 0*2^3 + 0*2^2 + 0*2^1 + 1*2^0
          0 + 0 + 0 + 0 + 0 + 0 + 1 = 1
    10进制的结果为1
*/

// | 按位或
// let numOne = 5;
// let numTwo = 3;
// let result = numOne | numTwo;
// console.log(result);
//把5和3转换成二进制数(短除法)
// 5 =》 00000101     3 =》 00000011
/*
   高位         低位
    2^6         2^0   级别
     00000101
|    00000011     对应位置上的值只有有一个为1，结果就为1，如果两个都为1，结果为1，否则为0
  -----------------
     00000111

     二进制按位与计算后的结果为00000111

把二进制数转为十进制数
0           0    0    0    0    1    1   1
符号位      2^6  2^5  2^4  2^3  2^2  2^1  2^0
          0*2^6 + 0*2^5 + 0*2^4 + 0*2^3 + 1*2^2 + 1*2^1 + 1*2^0
          0 + 0 + 0 + 0 + 4 + 2 + 1 = 7
    10进制的结果为7
*/

//^ 按位异或
// let numOne = 5;
// let numTwo = 3;
// let result = numOne ^ numTwo;
// console.log(result);
//把5和3转换成二进制数(短除法)
// 5 =》 00000101     3 =》 00000011
/*
   高位         低位
    2^6         2^0   级别
     00000101
^    00000011     相同为0，不同为1
  -----------------
     00000110

     二进制按位与计算后的结果为00000110

把二进制数转为十进制数
0           0    0    0    0    1    1   0
符号位      2^6  2^5  2^4  2^3  2^2  2^1  2^0
          0*2^6 + 0*2^5 + 0*2^4 + 0*2^3 + 1*2^2 + 1*2^1 + 0*2^0
          0 + 0 + 0 + 0 + 4 + 2 + 0 = 6
    10进制的结果为6
*/

