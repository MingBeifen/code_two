//字面量

//数值字面量
let numOne = 1;
let numTwo = 1.1; 

//二进制（数据只能用0和1来进行表示）  数据以0b开头
let numThree = 0b1010;  
//二进制转为十进制的方法
/*
高位        低位
1      0      1      0
2^3   2^2    2^1    2^0
1*2^3+0*2^2+1*2^1+0*2^0  
8+0+2+0=10
*/
//八进制(数据只能用0-7进行表示)  数据以0o开头
let numFour = 0o123;
//八进制转为十进制的方法
/*
高位        低位
1          2         3
8^2       8^1       8^0
1*8^2 +   2*8^1  +  3*8^0  
64   +    16   +    3
83
*/
//十六进制(数据只能用0-9和a-f进行表示)  数据以0x开头
let numFive = 0x12;
//十六进制转为十进制的方法
/*
高位        低位
1           2        
16^1       16^0       
1*16^1 +   2*16^0
16+2=18
*/
console.log(numOne, numTwo, numThree, numFour, numFive);

//科学计数法
let numSix = 1.2e3;  // 1.2 * 10^3
console.log(numSix);